# ------------------------------------------------------------------ 2. 开火：射线 + 伤害管线
def fire_script():
    """§481/§482：点到射线求交 → 部位 → 护甲/穿透 → 信号加成 → 状态结算。"""
    return [
        RECV("开火"),
        # ① 射线 vs 圆目标（2D 俯视简化）
        SET("dx", SUB(V("目标X"), V("射线起点X"))),
        SET("dy", SUB(V("目标Y"), V("射线起点Y"))),
        SET("投影t", ADD(MUL(V("dx"), V("射线方向X")),
                         MUL(V("dy"), V("射线方向Y")))),
        SET("垂距平方", SUB(ADD(MUL(V("dx"), V("dx")), MUL(V("dy"), V("dy"))),
                            MUL(V("投影t"), V("投影t")))),
        SET("临时", MUL(V("目标半径"), V("目标半径"))),
        IFELSE(ANDn(GE(V("投影t"), 0), LE(V("投影t"), V("射线最大距")),
                    LE(V("垂距平方"), V("临时"))),
               [
                   SET("入射t", SUB(V("投影t"), SQRT(SUB(V("临时"), V("垂距平方"))))),
                   # 墙体遮挡：墙的 t 更小则命中墙（穿墙系数衰减）
                   IFELSE(ANDn(GE(V("墙体t"), 0), LT(V("墙体t"), V("入射t"))),
                          [SET("掩体系数", V("穿墙系数")), SET("命中", 1)],
                          SET("掩体系数", 1)),
                   SET("命中", 1), SET("命中部位", 0),
                   SET("距离", V("入射t")),
                   # 部位：由命中点相对目标中心的高度分段
                   SET("临时2", SUB(ADD(V("射线起点Y"), MUL(V("射线方向Y"), V("入射t"))),
                                    V("目标Y"))),
                   IF(LT(V("临时2"), -15), SET("命中部位", 1)),
                   IF(ANDn(GE(V("临时2"), -15), LT(V("临时2"), 0)), SET("命中部位", 2)),
                   IF(ANDn(GE(V("临时2"), 0), LT(V("临时2"), 15)), SET("命中部位", 3)),
                   IF(GE(V("临时2"), 15), SET("命中部位", 4)),
               ],
               [SET("命中", 0), SET("命中部位", 0), SET("结果", "未命中")]),
        IFELSE(EQ(V("命中"), 0), [], [
            SET("部位倍率", ITEM("部位倍率表", V("命中部位"))),
            # ② 距离衰减（简化为线性，远距 >1000 起衰减）
            SET("距离衰减", 1),
            IF(GT(V("距离"), 1000),
               SET("距离衰减", SUB(1, DIV(SUB(V("距离"), 1000), 4000)))),
            # ③ 护甲 / 穿透
            SET("护甲系数", 1),
            IFELSE(EQ(V("模式"), 1),
                   [  # CS：护甲是数值 + 头盔
                       IF(GT(V("目标护甲"), 0), SET("护甲系数", 0.5)),
                       IF(ANDn(EQ(V("命中部位"), 4), EQ(V("头盔"), 1)),
                          SET("护甲系数", MUL(V("护甲系数"), 0.6))),
                   ],
                   [  # 摸金：穿透等级是门槛
                       IFELSE(LT(V("弹药穿透"), V("护甲等级")),
                              SET("护甲系数", 0.15),
                              [IFELSE(EQ(V("弹药穿透"), V("护甲等级")),
                                      SET("护甲系数", 0.75),
                                      SET("护甲系数", 1))]),
                   ]),
            # ④ 和平精英：信号值只放大受击伤害（不掉血）
            SET("信号加成", 1),
            IF(ANDn(EQ(V("模式"), 2), LT(V("信号值"), 75)), SET("信号加成", 1.15)),
            IF(ANDn(EQ(V("模式"), 2), LT(V("信号值"), 50)), SET("信号加成", 1.3)),
            IF(ANDn(EQ(V("模式"), 2), LT(V("信号值"), 25)), SET("信号加成", 1.5)),
            # ⑤ 管线求值
            SET("实际伤害", MUL(MUL(MUL(MUL(MUL(V("基础伤害"), V("部位倍率")),
                                            V("距离衰减")), V("护甲系数")),
                                    V("信号加成")), V("掩体系数"))),
            SET("实际伤害", ROUND(V("实际伤害"))),
            SET("目标血量", SUB(V("目标血量"), V("实际伤害"))),
            IF(LE(V("目标血量"), 0), [SET("倒地", 1), SET("目标血量", 0)]),
            SET("结果", cat("命中 部位", V("命中部位"), " t", V("入射t"),
                            " 伤害", V("实际伤害"), " 剩余血", V("目标血量"))),
        ]),
    ]


# ------------------------------------------------------------------ 3. 后坐力 / 散布
def recoil_script():
    """§483：后坐力图案可复现；散布随连发/移动/跳跃增加，蹲下/开镜/急停减免。"""
    return [
        RECV("后坐力"),
        CHG("连发数", 1),
        SET("后坐垂直", MUL(V("连发数"), 1.2)),
        # 水平图案：前 5 发右、之后左（可复现的表，不用随机数）
        IFELSE(LE(V("连发数"), 5),
               SET("后坐水平", MUL(V("连发数"), 0.6)),
               SET("后坐水平", MUL(SUB(10, V("连发数")), -0.5))),
        SET("散布", ADD(V("基础散布"), MUL(V("连发数"), 0.8))),
        SET("散布", ADD(V("散布"), MUL(V("移动速度"), 0.15))),
        IF(EQ(V("蹲下"), 1), SET("散布", MUL(V("散布"), 0.6))),
        IF(EQ(V("开镜"), 1), SET("散布", MUL(V("散布"), 0.5))),
        IF(EQ(V("急停"), 1), SET("散布", V("基础散布"))),
        SET("结果", cat("第", V("连发数"), "发 后坐 ", V("后坐垂直"),
                        "/", V("后坐水平"), " 散布 ", V("散布"))),
    ]


